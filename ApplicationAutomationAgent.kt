package com.example.domain

import com.example.data.model.Application
import com.example.data.model.CandidateProfile
import com.example.data.model.Job

object ApplicationAutomationAgent {

    val WORKFLOW_STAGES = listOf(
        "Discovered",
        "Match Reviewed",
        "Eligible for Application",
        "Application Prepared",
        "Awaiting Candidate Approval",
        "Submitted",
        "Employer Response",
        "Interview",
        "Offer Received",
        "Contract Verification",
        "Visa Process",
        "Closed"
    )

    fun prepareApplication(candidate: CandidateProfile, job: Job): Application {
        val tailoredCv = """
            VERIFIED PROFESSIONAL CV — TAILORED FOR ${job.company.uppercase()}
            Candidate: ${candidate.fullName}
            Target Role: ${job.title} (${job.city}, ${job.country})
            
            EXECUTIVE PROFILE:
            Experienced ${candidate.currentJobTitle} with ${candidate.yearsExperience} years of proven expertise in ${candidate.primaryIndustry}. Demonstrated technical proficiency operating ${candidate.machineEquipment}. Licenced: ${candidate.licences}.
            
            EDUCATION & ACCREDITATION:
            • ${candidate.educationLevel} in ${candidate.fieldOfStudy}
            • Licences: ${candidate.licences} (Issued: ${candidate.licenceIssuingCountry})
            • Languages: ${candidate.languages}
            
            WORK HISTORY & RESPONSIBILITIES:
            • ${candidate.currentJobTitle} | Current
              Responsibilities: ${candidate.responsibilities}
              Key Machinery & Standards: ${candidate.machineEquipment}
            
            IMMIGRATION COMPLIANCE STATUS:
            • Eligible Track: ${job.visaTrack}
            • Citizenship: ${candidate.citizenship} | Relocation: Fully Available (${candidate.availabilityDate})
        """.trimIndent()

        val tailoredCoverLetter = """
            Date: ${java.text.SimpleDateFormat("dd MMMM yyyy", java.util.Locale.US).format(java.util.Date())}
            
            To: Talent Acquisition & Engineering Hiring Board
            Company: ${job.company}
            Location: ${job.city}, ${job.country}
            
            RE: Application for ${job.title} (Vacancy Ref: ${job.id})
            
            Dear Hiring Team at ${job.company},
            
            I am writing to formally submit my candidacy for the ${job.title} opening in ${job.city}. With ${candidate.yearsExperience} years of hands-on experience in ${candidate.primaryIndustry}, I have specialized in commissioning, operating, and maintaining ${candidate.machineEquipment}.
            
            Reviewing your stated requirements for ${job.title}, I noted your focus on ${job.requiredQualifications} and certified experience in ${job.requiredLicences}. In my current role as ${candidate.currentJobTitle}, I have directly managed:
            "${candidate.responsibilities}"
            
            Furthermore, I possess verified credentials including ${candidate.licences}. For language requirements, I maintain ${candidate.languages}, ensuring seamless technical collaboration.
            
            Regarding work authorization, I have reviewed the official requirements for the ${job.visaTrack} via ${job.officialVisaSource}. I am prepared to begin upon completion of formal visa processing and look forward to participating in your interview process.
            
            Yours sincerely,
            ${candidate.fullName}
            ${candidate.email} | ${candidate.phone}
        """.trimIndent()

        return Application(
            id = "app-" + job.id.replace("job-", ""),
            jobId = job.id,
            jobTitle = job.title,
            company = job.company,
            country = job.country,
            city = job.city,
            salaryDisplay = "€${job.grossSalaryMonthly.toInt()} / mo",
            status = "Application Prepared",
            appliedTimestamp = System.currentTimeMillis(),
            tailoredCvContent = tailoredCv,
            tailoredCoverLetter = tailoredCoverLetter,
            submissionMethod = if (job.applicationMethod == "API_DIRECT") "Official Partner API" else "Guided Portal Assistant",
            submissionReferenceId = null,
            candidateApproved = false,
            portalDirectUrl = job.sourceUrl,
            candidateNotes = "Tailored documents generated by AI agent. Pending candidate review and explicit authorization."
        )
    }

    fun submitApplication(application: Application): Application {
        val refCode = "JN-${application.country.take(2).uppercase()}-${System.currentTimeMillis() % 100000}"
        return application.copy(
            candidateApproved = true,
            status = "Submitted",
            submissionReferenceId = refCode,
            candidateNotes = "Submitted via ${application.submissionMethod}. Official tracking reference: $refCode"
        )
    }
}
